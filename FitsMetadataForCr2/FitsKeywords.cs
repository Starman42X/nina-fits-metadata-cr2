using System;
using System.Collections.Generic;
using System.Linq;
using NINA.Image.FileFormat.FITS;
using NINA.Image.ImageData;

namespace FitsMetadataForCr2 {

    public record FitsKeyword(string Key, string Value, string Comment);

    public static class FitsKeywords {
        // Describe the FITS data array itself, not the observation - meaningless for a raw file
        private static readonly HashSet<string> structural = new(StringComparer.OrdinalIgnoreCase) {
            "SIMPLE", "BITPIX", "NAXIS", "NAXIS1", "NAXIS2", "NAXIS3", "EXTEND", "BZERO", "BSCALE", "END"
        };

        /// <summary>
        /// The keywords N.I.N.A. writes into a FITS file for this image, generated by N.I.N.A.'s own FITS header code
        /// so they match a FITS file exactly (including headers added by other plugins).
        /// </summary>
        public static List<FitsKeyword> FromMetaData(ImageMetaData metaData) {
            var header = new FITSHeader(0, 0);
            header.PopulateFromMetaData(metaData);
            return header.HeaderCards
                .Where(c => !string.IsNullOrWhiteSpace(c.Key) && !structural.Contains(c.Key.Trim()))
                .Select(c => new FitsKeyword(c.Key.Trim(), Unquote(c.Value), c.Comment?.Trim() ?? string.Empty))
                .ToList();
        }

        // FITS strings are stored as 'text    ' with '' for a quote
        private static string Unquote(string value) {
            var v = value?.Trim() ?? string.Empty;
            if (v.Length >= 2 && v[0] == '\'' && v[^1] == '\'') {
                v = v[1..^1].Replace("''", "'").TrimEnd();
            }
            return v;
        }
    }
}
